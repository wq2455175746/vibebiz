class Workspace:
    def __init__(self, root: Path) -> None:
        self.root = root.resolve()
        self.root.mkdir(parents=True, exist_ok=True)

    def project_dir(self, project_id: str) -> Path:
        if not PROJECT_ID_RE.fullmatch(project_id):
            raise WorkspaceError("invalid project id")
        candidate = (self.root / project_id).resolve()
        if not candidate.is_relative_to(self.root):
            raise WorkspaceError("invalid project path")
        return candidate

    def exists(self, project_id: str) -> bool:
        return self.project_dir(project_id).is_dir()

    def init_project(self, project_id: str) -> Path:
        project = self.project_dir(project_id)
        project.mkdir(parents=True, exist_ok=True)
        for name, content in STARTER_FILES.items():
            target = project / name
            if not target.exists():
                target.write_text(content, encoding="utf-8")
        return project

    def _existing_project(self, project_id: str) -> Path:
        project = self.project_dir(project_id)
        if not project.is_dir():
            raise NotFoundError("project not found")
        return project

    def _resolve(self, project_id: str, rel_path: str) -> Path:
        project = self._existing_project(project_id)
        rel_path = rel_path.strip().lstrip("/")
        if not rel_path:
            raise WorkspaceError("path is required")
        target = (project / rel_path).resolve()
        if not target.is_relative_to(project):
            raise WorkspaceError("path is outside workspace")
        rel_parts = target.relative_to(project).parts
        if any(part in IGNORED_PARTS for part in rel_parts):
            raise WorkspaceError("path is not accessible")
        return target

    def list_files(self, project_id: str) -> list[dict]:
        project = self._existing_project(project_id)
        entries: list[dict] = []
        for path in sorted(project.rglob("*")):
            rel_parts = path.relative_to(project).parts
            if any(part in IGNORED_PARTS for part in rel_parts):
                continue
            stat = path.stat()
            entries.append(
                {
                    "path": path.relative_to(project).as_posix(),
                    "type": "dir" if path.is_dir() else "file",
                    "size": 0 if path.is_dir() else stat.st_size,
                    "mtime": int(stat.st_mtime * 1000),
                }
            )
        return entries

    def stats(self, project_id: str) -> dict:
        project = self._existing_project(project_id)
        file_size_bytes = 0
        file_count = 0
        dir_count = 0
        last_modified_at = 0
        for path in sorted(project.rglob("*")):
            rel_parts = path.relative_to(project).parts
            if any(part in IGNORED_PARTS for part in rel_parts):
                continue
            stat = path.stat()
            if path.is_dir():
                dir_count += 1
                continue
            file_count += 1
            file_size_bytes += stat.st_size
            last_modified_at = max(last_modified_at, int(stat.st_mtime * 1000))
        return {
            "fileSizeBytes": file_size_bytes,
            "fileCount": file_count,
            "dirCount": dir_count,
            "lastModifiedAt": last_modified_at,
        }

    def archive(self, project_id: str) -> bytes:
        project = self._existing_project(project_id)
        buffer = io.BytesIO()
        with tarfile.open(fileobj=buffer, mode="w:gz") as archive:
            for path in sorted(project.rglob("*")):
                rel_parts = path.relative_to(project).parts
                if any(part in IGNORED_PARTS for part in rel_parts) or path.is_dir():
                    continue
                archive.add(path, arcname=path.relative_to(project).as_posix(), recursive=False)
        return buffer.getvalue()

    def import_archive(self, project_id: str, data: bytes) -> None:
        project = self._existing_project(project_id)
        for child in project.iterdir():
            if child.name in IGNORED_PARTS:
                continue
            if child.is_dir():
                shutil.rmtree(child)
            else:
                child.unlink()
        try:
            with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as archive:
                for member in archive.getmembers():
                    if not member.isfile():
                        continue
                    rel = member.name.replace("\\", "/").lstrip("/")
                    if not rel or rel.startswith("../") or "/../" in rel:
                        raise WorkspaceError("invalid archive path")
                    if any(part in IGNORED_PARTS for part in rel.split("/")):
                        continue
                    target = (project / rel).resolve()
                    if not target.is_relative_to(project):
                        raise WorkspaceError("invalid archive path")
                    target.parent.mkdir(parents=True, exist_ok=True)
                    source = archive.extractfile(member)
                    if source is None:
                        continue
                    target.write_bytes(source.read())

        except tarfile.TarError as exc:
            raise WorkspaceError("invalid archive") from exc

    def read_file(self, project_id: str, rel_path: str) -> dict:
        path = self._resolve(project_id, rel_path)
        if not path.is_file():
            raise NotFoundError("file not found")
        stat = path.stat()
        if stat.st_size > MAX_TEXT_BYTES:
            raise TooLargeError("file is larger than 5MB")
        data = path.read_bytes()
        is_binary = b"\x00" in data[:8192]
        return {
            "path": path.relative_to(self._existing_project(project_id)).as_posix(),
            "content": "" if is_binary else data.decode("utf-8", errors="replace"),
            "version": content_version(data),
            "size": stat.st_size,
            "mtime": int(stat.st_mtime * 1000),
            "isBinary": is_binary,
        }

    def write_file(
        self, project_id: str, rel_path: str, content: str, base_version: str = ""
    ) -> dict:
        path = self._resolve(project_id, rel_path)
        if path.exists() and path.is_dir():
            raise WorkspaceError("target is a directory")

        if path.exists() and base_version:
            current = content_version(path.read_bytes())
            if current != base_version:
                raise ConflictError("version conflict")

        encoded = content.encode("utf-8")
        path.parent.mkdir(parents=True, exist_ok=True)
        fd, tmp_name = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.", suffix=".tmp")
        try:
            with os.fdopen(fd, "wb") as tmp:
                tmp.write(encoded)
            os.replace(tmp_name, path)
        finally:
            if os.path.exists(tmp_name):
                os.unlink(tmp_name)

        stat = path.stat()
        return {
            "path": path.relative_to(self._existing_project(project_id)).as_posix(),
            "version": content_version(encoded),
            "size": stat.st_size,
            "mtime": int(stat.st_mtime * 1000),
        }

    def preview_path(self, project_id: str, rel_path: str) -> Path:
        project = self._existing_project(project_id)
        if not rel_path:
            candidate = project / "index.html"
        else:
            candidate = self._resolve(project_id, rel_path)
            if candidate.is_dir():
                candidate = candidate / "index.html"

        if not candidate.exists():
            if not Path(rel_path).suffix:
                index = project / "index.html"
                if index.is_file():
                    return index
            raise NotFoundError("file not found")
        if not candidate.is_file():
            raise NotFoundError("file not found")
        return candidate


def content_version(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()[:12]
